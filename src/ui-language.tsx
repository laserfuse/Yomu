function translateUi(language: UiLanguage, message: string, values: Record<string, string | number | null | undefined> = {}): string {
  let translated = language === 'en' ? english[message] ?? message : message
  if (language === 'en' && translated === message) {
    const dynamicMessages: Array<[RegExp, string]> = [
      [/^Le fichier collection\.json est invalide dans « (.+) »\.$/, 'The collection.json file in “$1” is invalid.'],
      [/^Le dossier de « (.+) » ne correspond pas à ses métadonnées\.$/, 'The folder for “$1” does not match its metadata.'],
      [/^Un chapitre a des métadonnées invalides dans « (.+) »\.$/, 'A chapter in “$1” has invalid metadata.'],
      [/^Un chapitre n’appartient pas à « (.+) »\.$/, 'A chapter does not belong to “$1”.'],
      [/^Le dossier de bibliothèque n’a pas pu être ouvert : (.+)$/, 'Could not open the library folder: $1'],
      [/^Le fichier du chapitre « (.+) » est absent de l’archive\.$/, 'The chapter file “$1” is missing from the archive.'],
      [/^L’export ne peut pas inclure le lien symbolique « (.+) »\.$/, 'The export cannot include the symbolic link “$1”.'],
      [/^L’export ne peut pas inclure l’élément « (.+) »\.$/, 'The export cannot include the item “$1”.'],
    ]
    for (const [pattern, replacement] of dynamicMessages) {
      if (pattern.test(message)) {
        translated = message.replace(pattern, replacement)
        break
      }
    }
  }
  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
}

export function UiLanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<UiLanguage>('fr')
  const [isLoading, setIsLoading] = useState(() => Boolean(window.yomu))
  const [loadError, setLoadError] = useState('')

  useEffect(() => {
    let active = true
    const api = window.yomu
    if (!api) {
      return () => { active = false }
    }
    api.getUiLanguage()
      .then((savedLanguage) => { if (active) setLanguageState(savedLanguage) })
      .catch((reason: unknown) => {
        if (active) setLoadError(reason instanceof Error ? reason.message : 'Le réglage de langue de l’application n’a pas pu être chargé.')
      })
      .finally(() => { if (active) setIsLoading(false) })
    return () => { active = false }
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const setLanguage = useCallback(async (nextLanguage: UiLanguage) => {
    if (!window.yomu) throw new Error('L’application Windows Yomu est nécessaire pour enregistrer la langue.')
    await window.yomu.setUiLanguage(nextLanguage)
    setLanguageState(nextLanguage)
    setLoadError('')
  }, [])
  const t = useCallback(
    (message: string, values?: Record<string, string | number | null | undefined>) => translateUi(language, message, values),
    [language],
  )
  const value = useMemo(() => ({ language, isLoading, loadError, setLanguage, t }), [language, isLoading, loadError, setLanguage, t])

  return <UiLanguageContext.Provider value={value}>{children}</UiLanguageContext.Provider>
}
